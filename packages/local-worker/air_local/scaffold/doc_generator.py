"""Auto-Documentation Generator.

Analyzes a project's Python files and generates:
- README.md with features, usage, installation
- ARCHITECTURE.md with module/class/function map
- API.md with function signatures and docstrings

No protected files modified.
"""
from __future__ import annotations

import ast
import sys
from pathlib import Path
from typing import Any

from air_local import policy

try:
    _reconfigure = getattr(sys.stdout, "reconfigure", None)
    if _reconfigure is not None:
        _reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass


def _parse_file(file_path: str) -> dict:
    """Parse a Python file into a structured representation."""
    path = Path(file_path)
    try:
        source = path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return {}

    try:
        tree = ast.parse(source)
    except SyntaxError:
        return {}

    # Attach parent links so top-level functions can be detected below.
    for node in ast.walk(tree):
        for child in ast.iter_child_nodes(node):
            child.parent = node  # type: ignore[attr-defined]

    result: dict[str, Any] = {
        "path": str(path),
        "name": path.stem,
        "docstring": ast.get_docstring(tree) or "",
        "imports": [],
        "classes": [],
        "functions": [],
    }

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                result["imports"].append(alias.name)
        elif isinstance(node, ast.ImportFrom):
            module = node.module or ""
            for alias in node.names:
                result["imports"].append(f"{module}.{alias.name}")
        elif isinstance(node, ast.ClassDef):
            methods = []
            for item in node.body:
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    methods.append({
                        "name": item.name,
                        "args": [a.arg for a in item.args.args],
                        "docstring": ast.get_docstring(item) or "",
                        "is_private": item.name.startswith("_"),
                    })
            result["classes"].append({
                "name": node.name,
                "docstring": ast.get_docstring(node) or "",
                "methods": methods,
                "is_private": node.name.startswith("_"),
            })
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            # Only top-level functions (parent is the Module)
            if isinstance(getattr(node, "parent", None), ast.Module):
                result["functions"].append({
                    "name": node.name,
                    "args": [a.arg for a in node.args.args],
                    "docstring": ast.get_docstring(node) or "",
                    "is_private": node.name.startswith("_"),
                })

    return result


def generate_readme(folder_path: str) -> str:
    """Generate README.md for a project."""
    folder = Path(folder_path)
    py_files = [f for f in folder.rglob("*.py")
                if not f.name.startswith(".") and f.name != "__init__.py"]

    if not py_files:
        return "# Project\n\nNo Python files found.\n"

    # Find main entry point
    main_file = None
    for f in py_files:
        if f.stem in ("main", "app", "cli"):
            main_file = f
            break
    if not main_file:
        main_file = py_files[0]

    parsed = _parse_file(str(main_file))
    public_funcs = [f for f in parsed["functions"] if not f["is_private"]]
    public_classes = [c for c in parsed["classes"] if not c["is_private"]]

    lines: list[str] = []
    lines.append(f"# {folder.name}")
    lines.append("")
    lines.append("## Overview")
    lines.append("")
    if parsed["docstring"]:
        lines.append(parsed["docstring"])
    else:
        lines.append("A project generated by AIR.")
    lines.append("")
    lines.append("## Features")
    lines.append("")
    if public_funcs:
        for f in public_funcs:
            lines.append(f"- `{f['name']}({', '.join(f['args'])})`")
    if public_classes:
        for c in public_classes:
            lines.append(f"- Class `{c['name']}` with {len(c['methods'])} method(s)")
    if not public_funcs and not public_classes:
        lines.append("- See source files for details")
    lines.append("")
    lines.append("## Requirements")
    lines.append("")
    lines.append("- Python 3.12 or later")
    lines.append("")
    lines.append("## Installation")
    lines.append("")
    lines.append("```bash")
    lines.append("pip install -r requirements.txt")
    lines.append("```")
    lines.append("")
    lines.append("## Usage")
    lines.append("")
    lines.append("```bash")
    lines.append(f"python {main_file.name}")
    lines.append("```")
    lines.append("")
    lines.append("## Project Structure")
    lines.append("")
    for f in sorted(py_files):
        lines.append(f"- `{f.relative_to(folder)}`")
    lines.append("")
    lines.append("## License")
    lines.append("")
    lines.append("MIT")

    return "\n".join(lines)


def generate_architecture(folder_path: str) -> str:
    """Generate ARCHITECTURE.md with module/class/function map."""
    folder = Path(folder_path)
    py_files = [f for f in folder.rglob("*.py")
                if not f.name.startswith(".")]

    if not py_files:
        return "# Architecture\n\nNo Python files found.\n"

    lines: list[str] = []
    lines.append("# Architecture")
    lines.append("")
    lines.append("## Module Map")
    lines.append("")

    for f in sorted(py_files):
        parsed = _parse_file(str(f))
        rel = f.relative_to(folder)
        lines.append(f"### `{rel}`")
        lines.append("")
        if parsed["docstring"]:
            lines.append(f"{parsed['docstring']}")
            lines.append("")
        if parsed["classes"]:
            lines.append("**Classes:**")
            for c in parsed["classes"]:
                priv = " (private)" if c["is_private"] else ""
                lines.append(f"- `{c['name']}`{priv}")
                for m in c["methods"]:
                    mpriv = " (private)" if m["is_private"] else ""
                    args = ", ".join(m["args"])
                    lines.append(f"  - `{m['name']}({args})`{mpriv}")
            lines.append("")
        if parsed["functions"]:
            lines.append("**Functions:**")
            for fn in parsed["functions"]:
                priv = " (private)" if fn["is_private"] else ""
                args = ", ".join(fn["args"])
                lines.append(f"- `{fn['name']}({args})`{priv}")
            lines.append("")
        if parsed["imports"]:
            lines.append("**Imports:**")
            lines.append(f"  {', '.join(parsed['imports'][:5])}")
            lines.append("")

    lines.append("## Data Flow")
    lines.append("")
    lines.append("1. User provides input via CLI or GUI")
    lines.append("2. Main entry point processes input")
    lines.append("3. Business logic executes in core modules")
    lines.append("4. Results returned to user")
    lines.append("")

    return "\n".join(lines)


def generate_api_docs(folder_path: str) -> str:
    """Generate API.md with function signatures and docstrings."""
    folder = Path(folder_path)
    py_files = [f for f in folder.rglob("*.py")
                if not f.name.startswith(".")]

    if not py_files:
        return "# API Reference\n\nNo Python files found.\n"

    lines: list[str] = []
    lines.append("# API Reference")
    lines.append("")
    lines.append("Auto-generated by AIR documentation generator.")
    lines.append("")

    for f in sorted(py_files):
        parsed = _parse_file(str(f))
        rel = f.relative_to(folder)
        lines.append(f"## `{rel}`")
        lines.append("")

        if parsed["classes"]:
            lines.append("### Classes")
            lines.append("")
            for c in parsed["classes"]:
                priv = " (private)" if c["is_private"] else ""
                lines.append(f"#### `{c['name']}`{priv}")
                if c["docstring"]:
                    lines.append(f"{c['docstring']}")
                    lines.append("")
                for m in c["methods"]:
                    mpriv = " (private)" if m["is_private"] else ""
                    args = ", ".join(m["args"])
                    lines.append(f"##### `{m['name']}({args})`{mpriv}")
                    if m["docstring"]:
                        lines.append(f"{m['docstring']}")
                    lines.append("")

        if parsed["functions"]:
            lines.append("### Functions")
            lines.append("")
            for fn in parsed["functions"]:
                priv = " (private)" if fn["is_private"] else ""
                args = ", ".join(fn["args"])
                lines.append(f"#### `{fn['name']}({args})`{priv}")
                if fn["docstring"]:
                    lines.append(f"{fn['docstring']}")
                lines.append("")

    return "\n".join(lines)


def generate_all_docs(folder: str) -> dict:
    """Generate all documentation files for a project inside the job root."""
    try:
        target = policy.resolve(folder, must_exist=True)
    except (PermissionError, FileNotFoundError) as exc:
        return {"error": str(exc)}
    if not target.is_dir():
        return {"error": f"not a directory: {target}"}

    results: dict[str, str] = {}

    readme = generate_readme(str(target))
    policy.require_write(target / "README.md").write_text(readme, encoding="utf-8")
    results["README.md"] = readme

    arch = generate_architecture(str(target))
    policy.require_write(target / "ARCHITECTURE.md").write_text(arch, encoding="utf-8")
    results["ARCHITECTURE.md"] = arch

    api = generate_api_docs(str(target))
    policy.require_write(target / "API.md").write_text(api, encoding="utf-8")
    results["API.md"] = api

    return {"folder": str(target), "files": results}
